"""Move the existing PC port's constant maths out of DOS startup."""
import math
import struct


def write_math_tables(directory):
    # Preserve math_tables_init's half-scale PC values. Amiga BigSine has a
    # different scale/sampling; substituting it would change existing movement.
    sine = []
    for i in range(4096):
        value = math.sin(i * 2.0 * math.pi / 4096.0) * 16384.0
        sine.append(int(value + (0.5 if value >= 0 else -0.5)))
    k = math.tan(math.pi * 2200.0 / 8007)
    norm = 1.0 / (1.0 + 1.41421356237 * k + k * k)
    b0 = int(k * k * norm * 16384)
    a1 = int(2 * (k * k - 1) * norm * 16384)
    a2 = int((1 - 1.41421356237 * k + k * k) * norm * 16384)
    rows = [', '.join(map(str, sine[i:i + 16])) for i in range(0, len(sine), 16)]
    # Exactly represent the previous (float)milliseconds / 20.0f values in
    # unsigned 0.32, including their binary32 rounding at each 50 Hz phase.
    alpha = [int(struct.unpack('<f', struct.pack('<f', i / 20.0))[0] * (1 << 32))
             for i in range(20)]
    text = ('/* Generated by tools/dos_math.py from the existing C formulae. */\n'
            '#ifndef AB3D_DOS_MATH_TABLES_H\n#define AB3D_DOS_MATH_TABLES_H\n'
            '#define AB3D_DOS_SINE_VALUES { \\\n' +
            ', \\\n'.join(rows) + ' \\\n}\n' +
            '#define AB3D_DOS_INTERPOLATION_VALUES { ' + ', '.join(f'{v}u' for v in alpha) + ' }\n' +
            f'#define AB3D_DOS_FILTER_RATE 8007\n'
            f'#define AB3D_DOS_FILTER_B0 {b0}\n'
            f'#define AB3D_DOS_FILTER_A1 {a1}\n'
            f'#define AB3D_DOS_FILTER_A2 {a2}\n#endif\n')
    target = directory / 'math_tables_dos.h'
    if not target.exists() or target.read_text() != text:
        target.write_text(text, encoding='ascii')
