import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { authoredMovingFixture } from '../authoredMovingFixture';
import { encodeProject, decodeProject } from '../../src/model/project';
import { buildPlayableLevel } from '../../src/model/playableBuild';
import { applyCommand, setSourceStart } from '../../src/model/commands';
import { engineMechanismTrace, engineMechanismState, enginePlayerState } from '../engineCapture';

for (const kind of ['door', 'lift'] as const) test(`make an editable ${kind}, cancel safely, save, undo, reopen, run native motion and remove`, async ({ page }, info) => {
  test.setTimeout(90000);
  const fixture = authoredMovingFixture(kind);
  if (kind === 'door') fixture.document = applyCommand(fixture.document, setSourceStart(fixture.document, 1, fixture.neighbour.id, 20272, 20128));
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'make.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(fixture.document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(fixture.document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${fixture.room.id.replace('room-', '')}(?:\\s|$)`) }).click();
  const section = page.getByRole('region', { name: 'Create door or lift', exact: true });
  const make = section.getByRole('button', { name: `Make ${kind}`, exact: true });
  await make.click();
  const form = section.getByRole('form', { name: 'Authored mechanism settings' });
  await expect(form).toBeVisible(); await form.getByRole('spinbutton', { name: 'New mechanism top', exact: true }).focus();
  await page.keyboard.press('Escape'); await expect(form).toHaveCount(0);
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  await make.click();
  await form.getByRole('spinbutton', { name: 'New mechanism top', exact: true }).fill(String(fixture.mechanism.bottom + 1));
  await form.getByRole('button', { name: 'Apply mechanism', exact: true }).click();
  await expect(form.getByRole('alert')).toBeVisible(); await expect(page.locator('.dirty-dot')).toHaveCount(0);
  await form.getByRole('spinbutton', { name: 'New mechanism top', exact: true }).fill(String(fixture.mechanism.top));
  await form.getByRole('spinbutton', { name: 'New mechanism bottom', exact: true }).fill(String(fixture.mechanism.bottom));
  await form.getByRole('combobox', { name: 'New mechanism opening rule', exact: true }).selectOption(kind === 'door' ? '0' : '2');
  await form.getByRole('combobox', { name: 'New mechanism closing rule', exact: true }).selectOption(kind === 'door' ? '0' : '2');
  await form.getByRole('button', { name: 'Apply mechanism', exact: true }).click();
  await expect(section.getByRole('heading', { level: 3 })).toHaveText(`Authored ${kind}`);
  await expect(form.getByRole('alert')).toHaveCount(0);
  await form.getByRole('combobox', { name: 'New mechanism kind', exact: true }).selectOption(kind === 'door' ? 'lift' : 'door');
  await expect(form.getByRole('combobox', { name: 'New mechanism closing rule', exact: true })).toHaveValue('0');
  await form.getByRole('button', { name: 'Cancel mechanism draft', exact: true }).click();
  await expect(form.getByRole('combobox', { name: 'New mechanism kind', exact: true })).toHaveValue(kind);
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(make).toBeVisible();
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(section.getByRole('heading', { level: 3 })).toHaveText(`Authored ${kind}`);
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = info.outputPath('mechanism.ab3d'); await (await download).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path))), built = buildPlayableLevel(saved, -1);
  const mechanism = built.document.mechanisms.filter(item => item.kind === kind).at(-1)!;
  expect(saved.roomSource.rooms.find(room => room.id === fixture.room.id)!.moving!.kind).toBe(kind);
  expect(mechanism.current).toBe(mechanism.bottom);
  await page.locator('input[type=file]').setInputFiles(path);
  await page.getByRole('button', { name: new RegExp(`^Room ${fixture.room.id.replace('room-', '')}(?:\\s|$)`) }).click();
  await expect(section.getByRole('heading', { level: 3 })).toHaveText(`Authored ${kind}`);
  await page.getByRole('button', { name: 'Engine view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview.getByRole('status')).toContainText('zones loaded', { timeout: 60000 });
  if (kind === 'door') {
    const outside = built.topology!.cells.find(cell => cell.sourceId === fixture.neighbour.id)!.id;
    await expect.poll(async () => (await enginePlayerState(page)).zone).toBe(outside);
    await expect(section.getByRole('heading', { level: 3 })).toHaveText('Authored door');
  }
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest running');
  if (kind === 'door') {
    expect(await engineMechanismState(page, kind, mechanism.id)).toMatchObject({ current: mechanism.bottom });
    await page.frameLocator('iframe[title="Alien Breed game engine"]').locator('canvas').press('Space', { delay: 80 });
  }
  const trace = await engineMechanismTrace(page, kind, mechanism.id, true);
  expect(trace.some(state => state.current > mechanism.top && state.current < mechanism.bottom)).toBe(true);
  for (const state of trace) expect(state).toMatchObject({ plane: state.current, unsynchronizedWalls: 0 });
  await preview.getByRole('button', { name: 'Stop', exact: true }).click();
  await section.getByRole('button', { name: 'Remove mechanism', exact: true }).click();
  await expect(make).toBeVisible();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(section.getByRole('heading', { level: 3 })).toHaveText(`Authored ${kind}`);
});
