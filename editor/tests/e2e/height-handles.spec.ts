import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { roomHeightFixture, twoStoreyHeightTemplate } from '../roomHeightFixture';
import { decodeProject, encodeProject, openArchive, openProjectCandidate } from '../../src/model/project';
import { captureEngine, enginePlayerFeetFixed } from '../engineCapture';

test('graphical height gestures cancel cleanly, save committed source only, undo once and update native collision and rendering', async ({ page }, testInfo) => {
  test.setTimeout(90000); page.on('dialog', dialog => void dialog.accept());
  const fixture = roomHeightFixture(), start = fixture.original.zones[0]!.floor;
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'height-handles.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(fixture.document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(fixture.document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${fixture.from.id.replace(/^room-/, '')}`) }).click();
  await page.getByRole('button', { name: 'Split view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  const camera = { zone: Number(await preview.getAttribute('data-spawn-zone')), x: 20128, z: 20128, upper: 0, angle: 0 };
  const before = await captureEngine(page, camera);
  const handle = page.getByRole('slider', { name: 'Lower floor handle', exact: true });
  const drag = async () => {
    await page.getByRole('group', { name: 'Room height section', exact: true }).scrollIntoViewIfNeeded();
    await expect(handle.locator('circle')).toBeInViewport();
    const bounds = (await handle.locator('circle').boundingBox())!;
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2 - 24, { steps: 8 });
    await expect.poll(async () => Number(await handle.getAttribute('aria-valuenow'))).toBeLessThan(start);
  };
  await drag();
  const save = page.waitForEvent('download'); await page.keyboard.press('Control+s');
  const draftPath = testInfo.outputPath('height-drag-draft.ab3d'); await (await save).saveAs(draftPath);
  const saved = decodeProject(new Uint8Array(await readFile(draftPath)));
  expect(saved.roomSource).toEqual(fixture.document.roomSource);
  await page.keyboard.press('Escape'); await page.mouse.up();
  await expect(handle).toHaveAttribute('aria-valuenow', String(start));
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await drag(); await page.mouse.up();
  const height = Number(await handle.getAttribute('aria-valuenow'));
  expect(height).toBeLessThan(start); expect(Number.isInteger(height * 4)).toBe(true);
  await expect(page.getByRole('spinbutton', { name: 'Lower floor height', exact: true })).toHaveValue(String(height));
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(handle).toHaveAttribute('aria-valuenow', String(start));
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(handle).toHaveAttribute('aria-valuenow', String(height));
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export level', exact: true }).click();
  const gamePath = testInfo.outputPath('height-drag-game.zip'); await (await download).saveAs(gamePath);
  const game = openProjectCandidate(openArchive(new Uint8Array(await readFile(gamePath)), 'height-drag-game.zip')[0]!);
  expect(game.zones[game.starts[0]!.zone]!.floor).toBe(height);
  await expect(preview).toHaveAttribute('data-level-slot', '0');
  expect(await captureEngine(page, camera)).not.toBe(before);
  await page.screenshot({ path: testInfo.outputPath('graphical-height-split.png') });
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest running');
  await expect.poll(() => enginePlayerFeetFixed(page)).toBe(height * 256);
  await preview.getByRole('button', { name: 'Stop', exact: true }).click();
});

test('upper and lower handles support repeated keyboard edits, invalid relationships and Escape without losing selection', async ({ page }) => {
  const fixture = roomHeightFixture(twoStoreyHeightTemplate()), template = fixture.original.zones[fixture.from.recordZone]!;
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'upper-handles.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(fixture.document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(fixture.document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${fixture.from.id.replace(/^room-/, '')}`) }).click();
  const upper = page.getByRole('slider', { name: 'Upper ceiling handle', exact: true });
  await upper.focus(); await expect(page.getByRole('tooltip')).toContainText('Shift changes 4 units');
  await upper.press('ArrowUp'); await upper.press('ArrowUp');
  await expect(upper).toBeFocused(); await expect(upper).toHaveAttribute('aria-valuenow', String(template.upperCeiling - 0.5));
  await upper.press('Shift+ArrowDown'); await expect(upper).toHaveAttribute('aria-valuenow', String(template.upperCeiling + 3.5));
  await expect(page.getByRole('slider', { name: 'Lower floor handle', exact: true })).toHaveAttribute('aria-valuenow', String(template.floor));
  await upper.press('Escape'); await expect(upper).toBeFocused();
  // A large drag through its own floor is an invalid provisional air band.
  await upper.scrollIntoViewIfNeeded(); const knob = (await upper.locator('circle').boundingBox())!;
  await page.mouse.move(knob.x + knob.width / 2, knob.y + knob.height / 2); await page.mouse.down();
  await page.mouse.move(knob.x + knob.width / 2, knob.y + knob.height / 2 + 140, { steps: 8 });
  await expect(page.locator('.room-height-section [role=status]')).toContainText('upper ceiling must be above');
  await page.mouse.up();
  await expect(upper).toHaveAttribute('aria-valuenow', String(template.upperCeiling + 3.5));
  await expect(page.getByRole('alert')).toContainText('upper ceiling must be above');
  await upper.press('ArrowUp'); await expect(upper).toHaveAttribute('aria-valuenow', String(template.upperCeiling + 3.25));
  await expect(page.getByRole('alert')).toHaveCount(0);
});
