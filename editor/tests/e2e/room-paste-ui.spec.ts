import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { roomHeightFixture } from '../roomHeightFixture';
import { movingControllerCopyFixture } from '../movingControllerCopyFixture';
import { applyCommand, editRoomSource } from '../../src/model/commands';
import { setRoomControllerCopies } from '../../src/model/movingControllerCopies';
import { decodeProject, encodeProject } from '../../src/model/project';

test('room clipboard placement validates, cancels, commits one edit and selects the pasted group', async ({ page }, testInfo) => {
  const { document, from, to } = roomHeightFixture();
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'room-ui.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  const row = (id: string) => page.getByRole('button', { name: new RegExp(`^Room ${id.replace(/^room-/, '')}(?:\\s|$)`) });
  await row(from.id).click(); await row(to.id).click({ modifiers: ['Shift'] });
  const map = page.locator('canvas[aria-label="Level map"]'); await map.focus(); await page.keyboard.press('Control+c');
  await expect(page.getByRole('button', { name: 'Paste rooms', exact: true })).toBeEnabled();
  await page.keyboard.press('Control+v');
  const dialog = page.getByRole('dialog', { name: 'Place pasted rooms' });
  await expect(dialog).toBeVisible();
  const x = dialog.getByRole('spinbutton', { name: 'Room paste anchor X' }), z = dialog.getByRole('spinbutton', { name: 'Room paste anchor Z' });
  await x.fill('20000'); await z.fill('20000');
  await expect(dialog.getByRole('alert')).toContainText('overlap');
  await expect(dialog.getByRole('button', { name: 'Paste rooms here', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Use map cursor', exact: true }).focus(); await page.keyboard.press('Control+z');
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0); await expect(row(from.id)).toBeVisible();
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  await page.getByRole('button', { name: 'Paste rooms', exact: true }).click();
  await x.fill('10000'); await z.fill('20000');
  await expect(dialog.getByRole('status')).toContainText('Ready to paste 2 rooms');
  await page.screenshot({ path: testInfo.outputPath('room-paste-preview.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Paste rooms here', exact: true }).click(); await expect(dialog).toHaveCount(0);
  const first = `room-${document.roomSource.nextId}`, second = `room-${document.roomSource.nextId + 1}`;
  await expect(row(first)).toHaveAttribute('aria-pressed', 'true'); await expect(row(second)).toHaveAttribute('aria-pressed', 'true');
  await expect(map).toHaveAttribute('data-world-x', '10628'); await expect(map).toHaveAttribute('data-world-z', '20128');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath('room-paste-ui.ab3d'); await (await download).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path)));
  expect(saved.roomSource.rooms).toHaveLength(document.roomSource.rooms.length + 2);
  expect(saved.sourceStarts).toEqual(document.sourceStarts); expect(saved.files).toEqual(document.files);
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(row(first)).toHaveCount(0); await expect(row(second)).toHaveCount(0);
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(row(first)).toBeVisible();
  await row(from.id).click(); await map.focus(); await page.keyboard.press('Control+d');
  await expect(dialog).toBeVisible(); await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
});

test('copying a controlled room captures and lists its required adjoining rooms', async ({ page }) => {
  const fixture = movingControllerCopyFixture('door');
  const document = applyCommand(fixture.document, editRoomSource(setRoomControllerCopies(fixture.document, [fixture.copy])));
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'room-dependencies.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${fixture.copy.room.replace(/^room-/, '')}(?:\\s|$)`) }).click();
  await page.getByRole('button', { name: 'Copy rooms', exact: true }).click(); await page.getByRole('button', { name: 'Paste rooms', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Place pasted rooms' });
  await expect(dialog).toContainText('1 selected, plus 2 attached rooms');
  await dialog.locator('summary').click(); await expect(dialog.getByRole('listitem')).toHaveCount(3);
  await dialog.getByRole('button', { name: 'Cancel room paste' }).click();
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
});
