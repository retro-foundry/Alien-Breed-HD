import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { movingControllerCopyFixture } from '../movingControllerCopyFixture';
import { applyCommand, editRoomSource } from '../../src/model/commands';
import { copiedMechanismSettings, setRoomControllerCopies } from '../../src/model/movingControllerCopies';
import { decodeProject, encodeProject } from '../../src/model/project';
import { engineMechanismState, engineMechanismTrace } from '../engineCapture';

for (const kind of ['door', 'lift'] as const) test(`copied ${kind} controls validate, undo, save and drive independent native motion`, async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const fixture = movingControllerCopyFixture(kind), { copy } = fixture;
  const document = applyCommand(fixture.document, editRoomSource(setRoomControllerCopies(fixture.document, [copy])));
  const settings = copiedMechanismSettings(document.roomSource.controllerCopies![0]!), top = settings.top + 0.25;
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'copied-settings.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${copy.room.replace(/^room-/, '')}(?:\\s|$)`) }).click();
  const prefix = `copied ${kind} ${copy.room}`, section = page.getByRole('region', { name: prefix, exact: true });
  const form = section.getByRole('form', { name: `${prefix} movement range` });
  const upper = form.getByRole('spinbutton', { name: `${prefix} top destination` });
  await upper.fill(String(settings.bottom + 1));
  await expect(form.getByRole('alert')).toContainText('upper destination');
  await expect(form.getByRole('button', { name: 'Apply range', exact: true })).toBeDisabled();
  await upper.press('Escape'); await expect(upper).toHaveValue(String(settings.top));
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  await upper.fill(String(top)); await form.getByRole('button', { name: 'Apply range', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(upper).toHaveValue(String(settings.top));
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(upper).toHaveValue(String(top));
  const opening = section.getByRole('combobox', { name: `${prefix} opening rule` });
  await opening.selectOption({ label: 'Never' });
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(opening).toHaveValue(String(settings.openRule));
  await section.getByRole('checkbox', { name: 'Key 1', exact: true }).check();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(section.getByRole('checkbox', { name: 'Key 1', exact: true })).not.toBeChecked();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath(`${kind}-edited-settings.ab3d`); await (await download).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path)));
  expect(saved.files).toEqual(document.files);
  expect(copiedMechanismSettings(saved.roomSource.controllerCopies![0]!)).toMatchObject({ top, conditions: 0, openRule: settings.openRule });
  await page.screenshot({ path: testInfo.outputPath(`${kind}-copied-settings.png`), fullPage: true });
  await page.getByRole('button', { name: 'Engine view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  expect(await engineMechanismState(page, kind, 1)).toMatchObject({ top });
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest running');
  const trace = await engineMechanismTrace(page, kind, 1, false);
  expect(trace.at(-1)!.current).toBe(top);
  for (const state of trace) expect(state).toMatchObject({ plane: state.current, unsynchronizedWalls: 0 });
  expect(await engineMechanismState(page, kind, 0)).toMatchObject({ current: settings.current });
});
