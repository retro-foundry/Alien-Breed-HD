import { expect, test } from '@playwright/test';
import { authoredMovingFixture } from '../authoredMovingFixture';
import { roomSettings } from '../../src/model/roomHeights';
import { encodeProject } from '../../src/model/project';
import { engineMechanismTrace, engineMechanismState, captureEngine } from '../engineCapture';

for (const kind of ['door', 'lift'] as const) test(`independently authored ${kind} cycles through native plane, wall and collision attachments`, async ({ page }, info) => {
  test.setTimeout(90000);
  const fixture = authoredMovingFixture(kind), document = fixture.built.document, mechanism = fixture.mechanism;
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'authored-moving.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.getByRole('button', { name: 'Engine view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview.getByRole('status')).toContainText('zones loaded', { timeout: 60000 });
  expect(await engineMechanismState(page, kind, mechanism.id)).toMatchObject({ current: mechanism.current, top: mechanism.top, bottom: mechanism.bottom, wallCount: 2 });
  const adjacent = roomSettings(fixture.document, fixture.neighbour);
  const camera = { zone: fixture.built.topology.cells.find(cell => cell.sourceId === fixture.neighbour.id)!.id, x: 20384, z: 20128, upper: 0, angle: 6144, height: (adjacent.floor + adjacent.ceiling) / 2 };
  await captureEngine(page, camera);
  await page.frameLocator('iframe[title="Alien Breed game engine"]').locator('canvas').screenshot({ path: info.outputPath('authored-initial.png') });
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest running');
  const setPlaying = (playing: boolean) => page.evaluate(playing => { window.document.querySelector<HTMLIFrameElement>('iframe[title="Alien Breed game engine"]')!.contentWindow!.postMessage({ source: 'ab3d-editor', type: 'play', playing }, location.origin); }, playing);
  const opening = await engineMechanismTrace(page, kind, mechanism.id, false);
  await setPlaying(false);
  const topHash = await captureEngine(page, camera);
  await page.frameLocator('iframe[title="Alien Breed game engine"]').locator('canvas').screenshot({ path: info.outputPath('authored-top.png') });
  await setPlaying(true);
  const closing = await engineMechanismTrace(page, kind, mechanism.id, true);
  await setPlaying(false);
  const bottomHash = await captureEngine(page, camera);
  expect(topHash).not.toBe(0); expect(bottomHash).not.toBe(0);
  expect(topHash).not.toBe(bottomHash);
  await page.frameLocator('iframe[title="Alien Breed game engine"]').locator('canvas').screenshot({ path: info.outputPath('authored-bottom.png') });
  const trace = [...opening, ...closing];
  expect(trace.some(state => state.current > mechanism.top && state.current < mechanism.bottom)).toBe(true);
  expect(trace.some(state => state.current === mechanism.top)).toBe(true);
  expect(trace.at(-1)!.current).toBe(mechanism.bottom);
  for (const state of trace) expect(state).toMatchObject({ zone: mechanism.zone, plane: state.current, unsynchronizedWalls: 0, wallCount: 2 });
  await preview.getByRole('button', { name: 'Stop', exact: true }).click();
  await expect(preview.getByRole('alert')).toHaveCount(0);
});
