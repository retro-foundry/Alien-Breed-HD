import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { objectStoreyFixture } from '../objectStoreyFixture';
import { applyCommand, numberPatch } from '../../src/model/commands';
import { encodeProject, decodeProject } from '../../src/model/project';
import { engineObjectState } from '../engineCapture';

test('group height offsets and alignment preserve floor bindings and native half-unit heights', async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const fixture = objectStoreyFixture();
  const base = fixture.document.objects[fixture.ids[0]!]!.y;
  const document = applyCommand(fixture.document, { label: 'Height fixture', patches: fixture.ids.map((id, index) => numberPatch(fixture.document, 'data', fixture.document.objects[id]!.offset + 4, (base - index * 2.5) * 2, 2)) });
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'group-heights.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.getByRole('tab', { name: 'Objects', exact: true }).click();
  await page.getByRole('button', { name: `Health ${fixture.ids[0]}`, exact: true }).click();
  await page.getByRole('button', { name: `Health ${fixture.ids[1]}`, exact: true }).click({ modifiers: ['Shift'] });
  const inspector = page.getByRole('complementary', { name: 'Object group inspector' });
  const offset = inspector.getByRole('spinbutton', { name: 'Group height offset', exact: true });
  await offset.fill('-2.5'); await inspector.getByRole('button', { name: 'Offset selected heights', exact: true }).click();
  await page.getByRole('button', { name: 'Engine view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  await expect.poll(async () => (await engineObjectState(page, fixture.ids[0]!)).yFixed).toBe((base - 2.5) * 256);
  expect((await engineObjectState(page, fixture.ids[1]!)).yFixed).toBe((base - 5) * 256);
  await inspector.getByRole('button', { name: 'Align heights', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await offset.fill('20000'); await inspector.getByRole('button', { name: 'Offset selected heights', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('No group heights were changed');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath('group-heights.ab3d'); await (await download).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path)));
  expect(fixture.ids.map(id => saved.objects[id]!.y)).toEqual([base - 2.5, base - 2.5]);
  expect(fixture.ids.map(id => saved.objects[id]!.upper)).toEqual([true, true]);
  expect(saved.sourceObjects).toEqual(document.sourceObjects);
  await expect.poll(async () => (await engineObjectState(page, fixture.ids[1]!)).yFixed).toBe((base - 2.5) * 256);
});
