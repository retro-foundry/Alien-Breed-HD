import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { nativeRoomCopyFixture } from '../nativeRoomCopyFixture';
import { twoStoreyHeightTemplate } from '../roomHeightFixture';
import { buildPlayableLevel } from '../../src/model/playableBuild';
import { encodeProject, decodeProject } from '../../src/model/project';
import { polygonMaterialTarget } from '../../src/model/polygonMaterials';
import { roomSourceSnapshot } from '../../src/model/roomSource';
import { captureEngine, enginePickDetails, enginePlayerState } from '../engineCapture';

for (const upper of [false, true]) for (const type of [1, 2]) test(`paint a ${upper ? 'upper' : 'lower'} ${type === 1 ? 'floor' : 'ceiling'} with all original patterns, repeat, history and portable source`, async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const { document, copy, original, dx, dz } = nativeRoomCopyFixture(upper ? twoStoreyHeightTemplate() : 0), built = buildPlayableLevel(document, -1);
  const cell = built.topology!.cells.find(cell => cell.sourceId === copy.id)!;
  const zone = built.document.zones[cell.id]!;
  const camera = { zone: cell.id, x: Math.round(copy.vertices.reduce((sum, p) => sum + p.x, 0) / copy.vertices.length),
    z: Math.round(copy.vertices.reduce((sum, p) => sum + p.z, 0) / copy.vertices.length), upper: upper ? 1 : 0, angle: 0,
    height: type === 1 ? (upper ? zone.upperFloor : zone.floor) - 1 : (upper ? zone.upperCeiling : zone.ceiling) + 1 };
  const originalCamera = { ...camera, zone: built.topology!.cells.find(cell => cell.sourceId === original.id)!.id, x: camera.x - dx, z: camera.z - dz };
  await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'surface.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.getByRole('button', { name: new RegExp(`^Room ${copy.id.replace(/^room-/, '')}`) }).click();
  await page.getByRole('button', { name: 'Engine view', exact: true }).click(); // Native rendering verification; editable 3D painting has its own scenarios.
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview.getByRole('status')).toContainText('zones loaded', { timeout: 60000 });
  if (upper) await page.getByRole('button', { name: 'Upper', exact: true }).click();
  const originalHash = await captureEngine(page, originalCamera), beforeHash = await captureEngine(page, camera);
  const points = Array.from({ length: 361 }, (_, index) => ({ x: (index % 19 + 1) / 20, y: (Math.floor(index / 19) + 1) / 20 }));
  const before = await enginePickDetails(page, points), index = before.findIndex(pick => pick.surface?.type === type && polygonMaterialTarget(built, pick.zone, pick.surface)?.room === copy.id);
  expect(index).toBeGreaterThanOrEqual(0);
  const pick = before[index]!, target = polygonMaterialTarget(built, pick.zone, pick.surface!)!;
  const record = (upper ? built.document.zones[pick.zone]!.upper : built.document.zones[pick.zone]!.lower).find(record => record.offset === pick.surface!.offset)!;
  const canvas = page.frameLocator('iframe[title="Alien Breed game engine"]').locator('canvas'), rect = (await canvas.boundingBox())!, point = points[index]!;
  const position = await enginePlayerState(page);
  await canvas.click({ position: { x: point.x * rect.width, y: point.y * rect.height } });
  await page.getByRole('button', { name: 'Paint this surface', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Paint floor or ceiling material' });
  const patterns = dialog.getByRole('group', { name: 'Floor pattern choices' });
  await expect(patterns.getByRole('button')).toHaveCount(16);
  await expect(patterns.getByRole('img')).toHaveCount(16);
  await expect(dialog.getByRole('alert')).toHaveCount(0);
  const pattern = record.texture === 771 ? 0 : 15, texture = pattern === 15 ? 771 : 0;
  await patterns.getByRole('button', { name: `Choose surface pattern ${pattern + 1}`, exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Surface texture repeat' }).selectOption('-5');
  await page.screenshot({ path: testInfo.outputPath('floor-pattern-draft.png'), fullPage: true });
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  expect(await captureEngine(page, camera)).toBe(beforeHash);
  await canvas.click({ position: { x: point.x * rect.width, y: point.y * rect.height } });
  await page.getByRole('button', { name: 'Paint this surface', exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Surface pattern' }).selectOption(String(texture));
  await dialog.getByRole('combobox', { name: 'Surface texture repeat' }).selectOption('-5');
  const revision = (await preview.getAttribute('data-revision'))!;
  await dialog.getByRole('button', { name: 'Apply surface material', exact: true }).click();
  await expect(dialog).toHaveCount(0); await expect(preview).not.toHaveAttribute('data-revision', revision);
  await expect(preview.getByRole('status')).toContainText('zones loaded');
  const paintedHash = await captureEngine(page, camera); expect(paintedHash).not.toBe(beforeHash);
  const after = await enginePickDetails(page, points);
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const file = testInfo.outputPath('painted-surface.ab3d'); await (await download).saveAs(file);
  const saved = decodeProject(new Uint8Array(await readFile(file))), rebuilt = buildPlayableLevel(saved, -1);
  expect(saved.files).toEqual(document.files); expect(roomSourceSnapshot(saved.roomSource).version).toBe(11);
  expect(saved.roomSource.rooms.find(room => room.id === copy.id)!.polygonMaterials).toEqual([{ record: target.record, upper, texture, scale: -5, mode: 'normal' }]);
  const changed = after.filter((pick, index) => pick.pixel !== before[index]!.pixel);
  expect(changed.length).toBeGreaterThan(0);
  for (const pick of changed) expect(polygonMaterialTarget(rebuilt, pick.zone, pick.surface!)).toEqual(target);
  expect(await captureEngine(page, originalCamera)).toBe(originalHash);
  for (const [name, checksum] of [['Undo', beforeHash], ['Redo', paintedHash]] as const) {
    const revision = (await preview.getAttribute('data-revision'))!;
    await page.getByRole('button', { name, exact: true }).click();
    await expect(preview).not.toHaveAttribute('data-revision', revision); await expect(preview.getByRole('status')).toContainText('zones loaded');
    expect(await captureEngine(page, camera)).toBe(checksum);
  }
  expect(await enginePlayerState(page)).toEqual(position);
  const previousFrame = await page.locator('iframe[title="Alien Breed game engine"]').elementHandle();
  await page.locator('input[type=file]').setInputFiles(file);
  await expect.poll(() => previousFrame!.evaluate(node => node.isConnected)).toBe(false);
  await expect(preview.getByRole('status')).toContainText('zones loaded');
  expect(await captureEngine(page, camera)).toBe(paintedHash);
  await canvas.click({ position: { x: point.x * rect.width, y: point.y * rect.height } });
  await page.getByRole('button', { name: 'Paint this surface', exact: true }).click();
  const resetRevision = (await preview.getAttribute('data-revision'))!;
  await dialog.getByRole('button', { name: 'Reset surface material', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(preview).not.toHaveAttribute('data-revision', resetRevision);
  await expect(preview.getByRole('status')).toContainText('zones loaded');
  expect(await captureEngine(page, camera)).toBe(beforeHash);
});
