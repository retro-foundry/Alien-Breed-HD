    for (const state of trace) expect(state).toMatchObject({ plane: state.current, unsynchronizedWalls: 0 });
    const oldZone = built.topology!.cells.find(cell => cell.sourceId === settings.room)!.id;
    expect((await engineRoomPlanes(page, oldZone))[kind === 'door' ? 'ceiling' : 'floor']).toBe(kind === 'door' ? settings.top : settings.current);
    await expect(preview.getByRole('alert')).toHaveCount(0);
