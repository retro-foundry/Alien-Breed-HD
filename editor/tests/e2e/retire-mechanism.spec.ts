    test.setTimeout(90000);
    const { document } = fixtureWithStaticStart(kind);
    const owner = mechanismSettingsOwners(document, kind).find(item => item.owner.type === type)!.owner as ImportedMechanismOwner;
    const settings = retiringMechanismSettings(document, owner), sourceRoom = document.roomSource.rooms.find(room => room.id === settings.room)!;
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('/?view=top'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
    await page.locator('input[type=file]').setInputFiles({ name: 'retire-controller.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
    await expect(page.locator('.project-picker strong')).toHaveText(document.name);
    const select = type === 'native' ? new RegExp(`^Zone ${String(sourceRoom.originZone).padStart(3, '0')}(?:\\s|$)`) : new RegExp(`^Room ${sourceRoom.id.replace(/^room-/, '')}(?:\\s|$)`);
    await page.getByRole('button', { name: select }).click();
    const panel = page.locator('.mechanism-retirement'); await panel.locator('summary').click();
    await panel.getByRole('spinbutton', { name: 'Old room static height' }).fill(String(settings.bottom + 1));
    await panel.getByRole('button', { name: 'Remove movement', exact: true }).click(); await expect(panel.getByRole('alert')).toContainText('between');
    await expect(page.locator('.dirty-dot')).toHaveCount(0);
    await panel.getByRole('button', { name: 'Cancel removal draft' }).click(); await expect(panel.getByRole('alert')).toHaveCount(0);
    await panel.getByRole('combobox', { name: 'Controller removal action' }).selectOption('move');
    await panel.getByText('Browse reassigned moving wall materials', { exact: true }).click();
    await expect(panel.getByRole('group', { name: 'reassigned moving wall material choices' })).toBeVisible();
    await panel.getByRole('combobox', { name: 'Imported mechanism destination room' }).selectOption(document.roomSource.rooms.find(room => room.moving)!.id);
    await panel.getByRole('button', { name: 'Move imported mechanism' }).click(); await expect(panel.getByRole('alert')).toContainText('already');
    await panel.getByRole('combobox', { name: 'Imported mechanism destination room' }).press('Escape');
    await expect(panel.getByRole('combobox', { name: 'Controller removal action' })).toHaveValue('remove');
    await expect(page.locator('.dirty-dot')).toHaveCount(0);
    await panel.getByRole('button', { name: 'Remove movement', exact: true }).click(); await expect(panel).toHaveCount(0);
    if (type === 'native' && kind === 'door') await expect(page.getByRole('button', { name: select }).locator('.door-dot')).toHaveCount(0);
    await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(panel).toBeVisible();
    await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(panel).toHaveCount(0);
    const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
    const path = info.outputPath(`retired-${type}-${kind}.ab3d`); await (await download).saveAs(path);
    const saved = decodeProject(new Uint8Array(await readFile(path))), built = buildPlayableLevel(saved, -1);
    expect(saved.files).toEqual(document.files); expect(built.document.mechanisms).toHaveLength(2);
    const zone = built.topology!.cells.find(cell => cell.sourceId === settings.room)!.id, height = kind === 'door' ? settings.top : settings.current;
    await page.getByRole('button', { name: 'Engine view', exact: true }).click();
    const preview = page.getByRole('region', { name: '3D game engine preview' }); await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
    expect((await engineRoomPlanes(page, zone))[kind === 'door' ? 'ceiling' : 'floor']).toBe(height);
    for (const control of built.document.mechanisms) expect(await engineMechanismState(page, kind, control.id)).toMatchObject({ current: control.current, plane: control.current, unsynchronizedWalls: 0 });
