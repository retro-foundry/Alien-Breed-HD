import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { decodeProject, openArchive } from '../../src/model/project';
import { openLevel } from '../../src/model/level';
import { originalFiles } from '../helpers';

test('saved and exported exits drive actual game completion and can be cleared', async ({ page }, testInfo) => {
  test.setTimeout(90000);
  page.on('dialog', dialog => void dialog.accept());
  await page.goto('/');
  await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  const spawn = openLevel('original', originalFiles(1)).starts[0]!.zone;
  const exit = page.getByRole('combobox', { name: 'Level exit', exact: true });
  await exit.selectOption(String(spawn));
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(exit).toHaveValue('original');
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(exit).toHaveValue(String(spawn));
  const saved = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const projectPath = testInfo.outputPath('spawn-exit.ab3d'); await (await saved).saveAs(projectPath);
  expect(decodeProject(new Uint8Array(await readFile(projectPath))).exitZone).toBe(spawn);
  const exported = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export level', exact: true }).click();
  const gamePath = testInfo.outputPath('spawn-exit-game.zip'); await (await exported).saveAs(gamePath);
  expect(openArchive(new Uint8Array(await readFile(gamePath)), 'level.zip')[0]!.exitZone).toBe(spawn);
  await page.getByRole('button', { name: '3D view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview).toHaveAttribute('data-exit-zone', String(spawn), { timeout: 60000 });
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest ended. Build and play again to restart.');
  await exit.selectOption('-1');
  await expect(preview).toHaveAttribute('data-exit-zone', '-1');
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest running');
  await preview.getByRole('button', { name: 'Stop', exact: true }).click();
  await exit.selectOption('original');
  await expect(preview).toHaveAttribute('data-exit-zone', '132');
  await page.locator('input[type=file]').setInputFiles(gamePath);
  await expect(exit).toHaveValue(String(spawn));
  await expect(preview).toHaveAttribute('data-exit-zone', String(spawn));
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('status')).toHaveText('Playtest ended. Build and play again to restart.');
});
