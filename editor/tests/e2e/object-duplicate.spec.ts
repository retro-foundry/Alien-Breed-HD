import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { roomHeightFixture } from '../roomHeightFixture';
import { createObject, objectTemplates } from '../../src/model/objectAuthoring';
import { applyCommand, numberPatch } from '../../src/model/commands';
import { decodeProject, encodeProject } from '../../src/model/project';
import { engineObjectState } from '../engineCapture';

test('duplicate drafts copy authored coordinates and exact settings, cancel safely and create independent native records', async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const fixture = roomHeightFixture(), template = objectTemplates(fixture.document).find(object => object.type === 0)!;
  const proposal = createObject(fixture.document, { template: template.id, room: fixture.from.id, x: 20128.5, z: 20192.25, y: -7.5 });
  let document = applyCommand(fixture.document, proposal.command);
  document = applyCommand(document, { label: 'Fixture health', patches: [numberPatch(document, 'data', document.objects[proposal.id]!.offset + 18, 23, 1)] });
  const copyId = document.objects.length;
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').setInputFiles({ name: 'duplicate.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(document.name);
  await page.locator('canvas[aria-label="Level map"]').focus(); await page.keyboard.press('Control+d');
  await expect(page.getByRole('dialog', { name: 'Add object', exact: true })).toHaveCount(0);
  await expect(page.locator('.status-message')).toContainText('Select an enemy, pickup or scenery');
  await page.getByRole('tab', { name: 'Objects', exact: true }).click();
  await page.getByRole('button', { name: `Alien ${proposal.id}`, exact: true }).click();
  await page.keyboard.press('Control+d');
  const dialog = page.getByRole('dialog', { name: 'Add object', exact: true });
  await expect(dialog.getByRole('heading')).toHaveText(`Duplicate Alien ${proposal.id}`);
  await expect(dialog.getByRole('combobox', { name: 'New object template' })).toHaveValue(String(proposal.id));
  await expect(dialog.getByRole('combobox', { name: 'New object room' })).toHaveValue(fixture.from.id);
  await expect(dialog.getByRole('spinbutton', { name: 'New object X', exact: true })).toHaveValue('20128.5');
  await expect(dialog.getByRole('spinbutton', { name: 'New object height', exact: true })).toHaveValue('-7.5');
  await expect(dialog.getByRole('checkbox', { name: 'Match template floor offset' })).not.toBeChecked();
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  await page.getByRole('button', { name: 'Duplicate object', exact: true }).click();
  await dialog.getByRole('spinbutton', { name: 'New object X', exact: true }).fill('20144.5');
  await dialog.getByRole('button', { name: 'Create object', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Health', exact: true })).toHaveValue('23');
  await page.getByRole('spinbutton', { name: 'Health', exact: true }).focus(); await page.keyboard.press('Control+d');
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: `Alien ${copyId}`, exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath('duplicated.ab3d'); await (await download).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path)));
  expect(saved.objects).toHaveLength(copyId + 1);
  expect(saved.objects[copyId]).toMatchObject({ x: 20144.5, z: 20192.25, y: -7.5, health: 23, type: 0 });
  expect(saved.objects[copyId]!.cid).not.toBe(saved.objects[proposal.id]!.cid);
  expect(saved.objects[proposal.id]).toMatchObject({ x: 20128.5, z: 20192.25, y: -7.5, health: 23 });
  await page.getByRole('button', { name: 'Add object', exact: true }).click();
  await expect(dialog.getByRole('combobox', { name: 'New object template' })).toHaveValue('');
  await dialog.getByRole('button', { name: 'Cancel object', exact: true }).click();
  await page.getByRole('button', { name: '3D view', exact: true }).click();
  await expect(page.getByRole('region', { name: '3D game engine preview' })).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  expect(await engineObjectState(page, proposal.id)).toMatchObject({ x: 20128.5, z: 20192.25, yFixed: -7.5 * 256, health: 23 });
  expect(await engineObjectState(page, copyId)).toMatchObject({ x: 20144.5, z: 20192.25, yFixed: -7.5 * 256, health: 23 });
});
