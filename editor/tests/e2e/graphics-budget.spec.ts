import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { graphicsBudgetFixture } from '../graphicsBudgetFixture';
import { decodeProject, encodeProject } from '../../src/model/project';
import { zoneGraphicsRecordLimit } from '../../src/model/renderLimits';
import { openLevel } from '../../src/model/level';
import { originalFiles } from '../helpers';
import { captureEngine } from '../engineCapture';

test('the final native graphics commands draw at the budget boundary, while overflow stops play/export and remains saveable', async ({ page }, testInfo) => {
  test.setTimeout(90000); page.on('dialog', dialog => void dialog.accept());
  const reference = openLevel('reference', originalFiles(1)), allowed = graphicsBudgetFixture(zoneGraphicsRecordLimit), overflow = graphicsBudgetFixture(zoneGraphicsRecordLimit + 1);
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.getByRole('button', { name: 'Engine view', exact: true }).click();
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  const start = reference.starts[0]!, before = [];
  for (const angle of [0, 2048, 4096, 6144]) before.push(await captureEngine(page, { ...start, upper: 0, angle }));
  const revision = await preview.getAttribute('data-revision');
  await page.locator('input[type=file]').setInputFiles({ name: 'budget-boundary.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(allowed)) });
  await expect(page.locator('.project-picker strong')).toHaveText(allowed.name);
  await expect(preview).not.toHaveAttribute('data-revision', revision!);
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  const after = [];
  for (const angle of [0, 2048, 4096, 6144]) after.push(await captureEngine(page, { ...start, upper: 0, angle }));
  expect(after).toEqual(before);
  await testInfo.attach('graphics-budget-frame-comparisons', { body: JSON.stringify({ limit: zoneGraphicsRecordLimit, before, after }), contentType: 'application/json' });
  await page.locator('input[type=file]').setInputFiles({ name: 'over-budget.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(overflow)) });
  await expect(page.locator('.project-picker strong')).toHaveText(overflow.name);
  await expect(preview.getByRole('alert')).toContainText(`Room 0 lower floor has ${zoneGraphicsRecordLimit + 1} graphics commands`);
  await expect(preview).not.toHaveAttribute('data-level-slot', '0');
  await preview.getByRole('button', { name: 'Build & play', exact: true }).click();
  await expect(preview.getByRole('alert')).toContainText(`Room 0 lower floor has ${zoneGraphicsRecordLimit + 1} graphics commands`);
  await expect(preview.getByRole('status')).not.toHaveText('Playtest running');
  const downloads: string[] = []; page.on('download', item => downloads.push(item.suggestedFilename()));
  await page.getByRole('button', { name: 'Export level', exact: true }).click();
  await expect(page.getByText(/Room 0 lower floor has .*graphics commands/).first()).toBeVisible();
  await expect(page.getByRole('button', { name: 'Export level', exact: true })).toBeEnabled();
  expect(downloads).toEqual([]);
  const savedDownload = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath('oversized-editable-project.ab3d'); await (await savedDownload).saveAs(path);
  const saved = decodeProject(new Uint8Array(await readFile(path)));
  expect(saved.files).toEqual(overflow.files); expect(saved.zones[0]!.lower).toHaveLength(zoneGraphicsRecordLimit + 1);
  await page.getByRole('button', { name: 'Help and shortcuts', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Engine capacity' })).toBeVisible();
  await expect(page.getByText(`The current game supports ${zoneGraphicsRecordLimit} graphics commands per room and floor.`, { exact: false })).toBeVisible();
});
