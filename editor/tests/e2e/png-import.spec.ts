import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import fixtures from '../fixtures/png-images.json' with { type: 'json' };
import { wallOverrideFixture } from '../wallOverrideFixture';
import { decodeProject, encodeProject, openArchive, openProjectCandidate } from '../../src/model/project';
import { captureEngine } from '../engineCapture';
import { strFromU8, unzipSync } from 'fflate';

test('PNG import fits, previews and cancels before one undoable native conversion; original image survives project recovery', async ({ page }, testInfo) => {
  test.setTimeout(120000); page.on('dialog', dialog => void dialog.accept());
  const fixture = wallOverrideFixture(), sourcePng = Buffer.from(fixtures.rgba4k, 'base64');
  await page.goto('/'); await expect(page.locator('.project-picker strong')).toHaveText('Level 1');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'png-project.ab3d', mimeType: 'application/zip', buffer: Buffer.from(encodeProject(fixture.document)) });
  await expect(page.locator('.project-picker strong')).toHaveText(fixture.document.name);
  const selectRoom = () => page.getByRole('button', { name: new RegExp(`^Room ${fixture.from.id.replace(/^room-/, '')}`) }).click();
  await selectRoom(); await page.getByRole('button', { name: 'Split view', exact: true }).click();
  const preview = page.getByRole('region', { name: '3D game engine preview' });
  await expect(preview).toHaveAttribute('data-level-slot', '0', { timeout: 60000 });
  const camera = { zone: Number(await preview.getAttribute('data-spawn-zone')), x: 20128, z: 20128, upper: 0, angle: 0 }, before = await captureEngine(page, camera);
  await page.getByText('Browse lower wall materials', { exact: true }).click();
  const input = page.getByLabel('Import lower wall PNG', { exact: true });
  await expect(input).toBeVisible();
  await input.setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from([137, 80, 78]) });
  await expect(page.getByRole('alert')).toContainText('valid PNG');
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  const importPng = (buffer = sourcePng) => input.setInputFiles({ name: 'green.png', mimeType: 'image/png', buffer });
  const converted = page.getByRole('group', { name: 'lower wall PNG conversion preview', exact: true });
  await importPng(Buffer.from(fixtures.alpha7x5, 'base64')); await expect(converted).toContainText(`7 × 5 → ${fixture.sheet.width} × ${fixture.sheet.rows}`);
  const saveDraft = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const draftPath = testInfo.outputPath('png-draft.ab3d'); await (await saveDraft).saveAs(draftPath);
  expect(decodeProject(new Uint8Array(await readFile(draftPath))).wallOverrides).toBeUndefined();
  await page.getByRole('button', { name: 'Cancel PNG', exact: true }).click(); await expect(converted).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await importPng(); await expect(converted).toBeVisible();
  await input.press('Escape'); await expect(converted).toHaveCount(0);
  await expect(input).toBeVisible();
  await importPng(); await expect(converted).toBeVisible();
  await expect(converted.getByRole('img')).toHaveCount(2);
  await converted.scrollIntoViewIfNeeded(); await page.mouse.move(0, 0);
  await page.screenshot({ path: testInfo.outputPath('png-conversion-comparison.png') });
  await page.getByRole('button', { name: 'Apply PNG', exact: true }).click(); await expect(converted).toHaveCount(0);
  await expect(preview).toHaveAttribute('data-level-slot', '0');
  const after = await captureEngine(page, camera); expect(after).not.toBe(before);
  // Reapplying identical native bytes and original source closes review without
  // adding a second edit or discarding the retained PNG.
  await importPng(); await expect(converted).toBeVisible();
  await page.getByRole('button', { name: 'Apply PNG', exact: true }).click(); await expect(converted).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await expect(preview).toHaveAttribute('data-level-slot', '0'); expect(await captureEngine(page, camera)).toBe(before);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(preview).toHaveAttribute('data-level-slot', '0'); expect(await captureEngine(page, camera)).toBe(after);
  const save = page.waitForEvent('download'); await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const path = testInfo.outputPath('png-source.ab3d'); await (await save).saveAs(path);
  const bytes = new Uint8Array(await readFile(path)), saved = decodeProject(bytes), entries = unzipSync(bytes);
  expect(JSON.parse(strFromU8(entries['alien-breed-project.json']!)).version).toBe(10);
  expect(saved.files).toEqual(fixture.document.files);
  expect(saved.wallOverrides![0]!.sourcePng).toEqual(new Uint8Array(sourcePng));
  expect(saved.wallOverrides![0]!.bytes.slice(0, 2048)).toEqual(fixture.original.slice(0, 2048));
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export level', exact: true }).click();
  const gamePath = testInfo.outputPath('png-native-game.zip'); await (await download).saveAs(gamePath);
  const game = openProjectCandidate(openArchive(new Uint8Array(await readFile(gamePath)), 'game.zip')[0]!);
  expect(game.wallOverrides![0]!.bytes).toEqual(saved.wallOverrides![0]!.bytes);
  expect(game.wallOverrides![0]!.sourcePng).toBeUndefined();
  await page.mouse.move(0, 0); await page.screenshot({ path: testInfo.outputPath('png-native-preview.png') });
  await expect(page.getByText('Workspace saved', { exact: true })).toBeVisible();
  await page.reload(); await expect(page.locator('.project-picker strong')).toHaveText(fixture.document.name);
  await selectRoom(); await page.getByText('Browse lower wall materials', { exact: true }).click();
  const originalDownload = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download original PNG', exact: true }).click();
  const pngPath = testInfo.outputPath('original.png'); await (await originalDownload).saveAs(pngPath);
  expect(await readFile(pngPath)).toEqual(sourcePng);
});
