import type { LevelDocument } from './level';
import { roomAppearanceBuildOptions } from './roomAppearance';
import { sourceMatchesLevel } from './roomSource';
import { buildSourceLevel } from './sourceBuild';
import type { RoomTopology } from './roomTopology';
import { assertPlayableGraphics } from './renderLimits';
import type { GeneratedGraphicIdentity } from './generatedGraphics';

export interface PlayableLevel { source: LevelDocument; document: LevelDocument; topology?: RoomTopology; surfaceSources?: readonly GeneratedGraphicIdentity[] }

export function buildPlayableLevel(source: LevelDocument, resolvedExit: number): PlayableLevel {
  if (sourceMatchesLevel(source)) { assertPlayableGraphics(source); return { source, document: source }; }
  const built = buildSourceLevel(source, { resolvedExit, ...roomAppearanceBuildOptions(source) });
  return { source, document: { ...built.document, ...(source.wallOverrides ? { wallOverrides: source.wallOverrides } : {}) }, topology: built.topology, surfaceSources: built.surfaceSources };
}

export function parseGameExitZones(value: unknown): readonly number[] {
  if (!value || typeof value !== 'object' || !('format' in value) || value.format !== 'alien-breed-game-config'
    || !('version' in value) || value.version !== 1 || !('exitZones' in value) || !Array.isArray(value.exitZones)
    || value.exitZones.length !== 16 || value.exitZones.some(zone => typeof zone !== 'number' || !Number.isInteger(zone) || zone < -1 || zone > 255))
    throw new Error('The packaged game configuration is invalid. Rebuild or reinstall the editor assets.');
  return Object.freeze([...value.exitZones]);
}

let gameConfig: Promise<readonly number[]> | undefined;
async function defaultExit(slot: number): Promise<number> {
  gameConfig ??= fetch(`${import.meta.env.BASE_URL}reference/game-config.json`).then(async response => {
    if (!response.ok) throw new Error('Could not load the game configuration. Check the editor asset installation and try again.');
    return parseGameExitZones(await response.json());
  }).catch(error => { gameConfig = undefined; throw error; });
  return (await gameConfig)[slot]!;
}

const artifacts = new WeakMap<LevelDocument, Promise<PlayableLevel>>();
/** Preview and Export share an immutable artifact, keyed by the complete source
 * document. Failed builds are retryable; no generated bytes enter source saves. */
export function preparePlayableLevel(source: LevelDocument): Promise<PlayableLevel> {
  const cached = artifacts.get(source);
  if (cached) return cached;
  const promise = (async () => {
    if (sourceMatchesLevel(source)) return buildPlayableLevel(source, -1);
    // Yield so controls can show the build state before the synchronous compiler.
    await new Promise(resolve => setTimeout(resolve, 0));
    return buildPlayableLevel(source, source.exitZone ?? await defaultExit(source.playtestSlot));
  })().catch(error => { artifacts.delete(source); throw error; });
  artifacts.set(source, promise); return promise;
}
